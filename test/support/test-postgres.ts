import {
  PostgreSqlContainer,
  type StartedPostgreSqlContainer,
} from '@testcontainers/postgresql';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { runMigrations } from '../../src/database/migrate.js';
import { POSTGRES_IMAGE } from './postgres-image.js';

export interface TestPostgres {
  // The URL of a new database, cloned from the migrated template or empty.
  createDatabase(options: { migrated: boolean }): Promise<string>;
  stop(): Promise<void>;
}

// One container per test file. The template database is migrated once with the
// real runner, so each `createDatabase({ migrated: true })` is a cheap copy.
// Credentials are generated by the container at runtime.
export async function startTestPostgres(): Promise<TestPostgres> {
  const container: StartedPostgreSqlContainer = await new PostgreSqlContainer(
    POSTGRES_IMAGE,
  ).start();
  const admin = new pg.Pool({ connectionString: container.getConnectionUri() });

  const urlFor = (database: string) => {
    const url = new URL(container.getConnectionUri());
    url.pathname = `/${database}`;
    return url.toString();
  };
  // Names are generated here, never taken from input, so quoting is enough.
  const newName = (prefix: string) =>
    `${prefix}_${randomUUID().replaceAll('-', '')}`;

  const template = newName('template');
  await admin.query(`CREATE DATABASE "${template}"`);
  const templatePool = new pg.Pool({ connectionString: urlFor(template) });
  try {
    await runMigrations(templatePool);
  } finally {
    // A database can only serve as a template while nobody is connected.
    await templatePool.end();
  }
  await admin.query(`ALTER DATABASE "${template}" WITH IS_TEMPLATE true`);

  return {
    async createDatabase({ migrated }) {
      const name = newName('test');
      await admin.query(
        migrated
          ? `CREATE DATABASE "${name}" TEMPLATE "${template}"`
          : `CREATE DATABASE "${name}"`,
      );
      return urlFor(name);
    },
    async stop() {
      await admin.end();
      await container.stop();
    },
  };
}
